package level1;

public class AveragePercentMarkInPCM {

	public static void main(String[] args) {
		double mathMarks = 94;
		double physicsMarks = 95;
		double chemistryMarks = 96;
		double marksSum = mathMarks + physicsMarks + chemistryMarks;
		double averageMarks = marksSum / 3;
		System.out.println("Sam’s average mark in PCM is " + averageMarks);

	}

}
